import type { WidgetMessage } from "../components/AgricultureChatWidget";
import type { Language } from "../translations";

export interface ChatSession {
  sessionId: string;
  clientIp?: string;
  title: string;
  createdAt: number;
  lastActivityAt: number;
  expiresAt: number;
  messages: WidgetMessage[];
  lang: Language;
}

export function generateSessionId(): string {
  const randomSuffix = Math.floor(100000 + Math.random() * 900000);
  return `cg_sess_${Date.now()}_${randomSuffix}`;
}

export function deriveSessionTitle(firstQuestion: string, lang: Language): string {
  const trimmed = firstQuestion.trim();
  if (!trimmed) {
    return lang === "hi" ? "नया कृषि परामर्श" : "New Agriculture Consultation";
  }
  if (trimmed.length <= 34) {
    return trimmed;
  }
  return trimmed.slice(0, 32) + "…";
}

/**
 * Exports consultation session as a formatted text file
 */
export function exportSessionTranscript(session: ChatSession): void {
  const dateFormatted = new Date(session.createdAt).toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    dateStyle: "medium",
    timeStyle: "short",
  });

  let transcript = `====================================================================\n`;
  transcript += `CHHATTISGARH AGRICULTURE AI ASSISTANT (कृषि AI सहायक)\n`;
  transcript += `OFFICIAL CONSULTATION RECORD / आधिकारिक परामर्श विवरण\n`;
  transcript += `====================================================================\n`;
  transcript += `Session ID     : ${session.sessionId}\n`;
  transcript += `Server IP      : ${session.clientIp || "Verified Client"}\n`;
  transcript += `Date & Time    : ${dateFormatted} IST\n`;
  transcript += `Topic          : ${session.title}\n`;
  transcript += `Language       : ${session.lang === "hi" ? "हिन्दी" : "English"}\n`;
  transcript += `Total Messages : ${session.messages.length}\n`;
  transcript += `====================================================================\n\n`;

  if (session.messages.length === 0) {
    transcript += `[No messages recorded in this consultation]\n`;
  } else {
    session.messages.forEach((msg, idx) => {
      const sender = msg.role === "user" ? "Kisan (Farmer)" : "Agriculture AI";
      transcript += `[${idx + 1}] ${sender}:\n${msg.text}\n`;
      if (msg.source) {
        transcript += `    * Source: ${msg.source.title} (${msg.source.department})\n`;
        if (msg.source.url) transcript += `    * URL: ${msg.source.url}\n`;
      }
      transcript += `\n--------------------------------------------------------------------\n\n`;
    });
  }

  transcript += `\nDisclaimer: Responses are generated by Chhattisgarh Agriculture AI based on\n`;
  transcript += `verified guidelines. For emergency farmer support, dial Helpline: 1800-180-1551.\n`;

  const blob = new Blob([transcript], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `${session.sessionId}_consultation.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
